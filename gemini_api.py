"""
Centralized Gemini AI Provider for G-AI-ASSISTANT.
Uses the modern Google Gen AI SDK (google-genai) with fallback support.
Handles model configuration, secure credential management, conversation history,
memory context injection, and structured error handling.
"""

import json
import logging
import re
from typing import Any, Dict, List, Optional

from config import get_secret, set_secret

logger = logging.getLogger(__name__)

# Modern verified Gemini models
DEFAULT_MODEL = "gemini-2.0-flash"
SUPPORTED_MODELS = [
    "gemini-2.0-flash",
    "gemini-2.5-flash",
    "gemini-2.5-pro",
    "gemini-1.5-flash",
    "gemini-1.5-pro",
]

VALID_INTENT_TYPES = {
    "launch_app",
    "open_url",
    "open_path",
    "web_search",
    "window_management",
    "create_task",
    "compose_email",
    "system_status",
    "general_chat",
}


def validate_intent_output(data: Dict[str, Any]) -> Dict[str, Any]:
    """
    Validates and sanitizes structured intent data generated by Gemini.
    Guarantees allowlist enforcement and confirmation requirements.
    """
    if not isinstance(data, dict):
        data = {}

    intent_type = str(data.get("intent_type", "general_chat")).strip().lower()
    if intent_type not in VALID_INTENT_TYPES:
        intent_type = "general_chat"

    response_text = str(data.get("response_text", "")).strip()
    if not response_text:
        response_text = "I've processed your request."

    params = data.get("parameters", {})
    if not isinstance(params, dict):
        params = {}

    urgency = str(data.get("urgency", "low")).strip().lower()
    if urgency not in ("low", "medium", "high", "critical"):
        urgency = "low"

    requires_confirmation = bool(data.get("requires_confirmation", False))

    # Action-specific security validation
    if intent_type == "launch_app":
        app_id = str(params.get("app_id", "")).strip().lower()
        from automation_service import APPROVED_APPS
        if app_id not in APPROVED_APPS:
            intent_type = "general_chat"
            response_text = f"Access Denied: Application '{app_id}' is not in the approved allowlist."
            params = {}
        else:
            requires_confirmation = True

    elif intent_type == "open_url":
        url = str(params.get("url", "")).strip()
        if ":" in url and not url.lower().startswith(("http://", "https://")):
            intent_type = "general_chat"
            response_text = "Security violation: Only HTTP and HTTPS URLs are permitted."
            params = {}

    elif intent_type == "open_path":
        raw_path = str(params.get("path", "") or params.get("file_or_folder_path", "")).strip()
        if ".." in raw_path:
            intent_type = "general_chat"
            response_text = "Security violation: Path traversal '..' is prohibited."
            params = {}
        else:
            requires_confirmation = True

    elif intent_type == "window_management":
        action = str(params.get("action", "")).strip().lower()
        app_id = str(params.get("app_id", "")).strip().lower()
        from automation_service import APPROVED_APPS
        if action not in ("minimize", "maximize", "restore", "focus") or app_id not in APPROVED_APPS:
            intent_type = "general_chat"
            response_text = f"Invalid window action or unapproved app '{app_id}'."
            params = {}
        else:
            requires_confirmation = True

    elif intent_type in ("compose_email", "create_task"):
        requires_confirmation = True

    return {
        "intent_type": intent_type,
        "response_text": response_text,
        "parameters": params,
        "urgency": urgency,
        "requires_confirmation": requires_confirmation,
    }


class GeminiAIProvider:
    """
    Centralized provider for interacting with Google Gemini models.
    Supports google-genai SDK, context injection, and secure credential handling.
    """

    DEFAULT_MODEL = DEFAULT_MODEL
    SUPPORTED_MODELS = SUPPORTED_MODELS

    def __init__(self):
        self._api_key: Optional[str] = None
        self._model_name: str = DEFAULT_MODEL
        self._client = None
        self._legacy_model = None
        self._use_modern_sdk: bool = True

        # Check SDK availability
        try:
            from google import genai
            self._use_modern_sdk = True
            logger.info("Using modern Google Gen AI SDK (google-genai).")
        except ImportError:
            self._use_modern_sdk = False
            logger.warning("google-genai not found, will attempt legacy google.generativeai.")

        logger.info("GeminiAIProvider initialized.")

    def is_configured(self) -> bool:
        """Returns True if the API key is configured."""
        return bool(self._api_key and self._api_key.strip())

    def save_api_key_securely(self, api_key: str) -> None:
        """Securely stores the Gemini API key."""
        if not api_key or not api_key.strip():
            raise ValueError("API key cannot be empty.")
        set_secret("gemini_api_key", api_key.strip())
        logger.info("Gemini API key saved securely.")

    def get_api_key_securely(self) -> Optional[str]:
        """Retrieves the Gemini API key from secure storage."""
        return get_secret("gemini_api_key")

    def set_api_key(self, api_key: Optional[str]) -> None:
        """Configures the API key for active client sessions."""
        if not api_key or not api_key.strip():
            self._api_key = None
            self._client = None
            self._legacy_model = None
            logger.warning("Gemini API key cleared.")
            return

        self._api_key = api_key.strip()
        self._initialize_client()

    def set_model(self, model_name: str) -> None:
        """Sets the active model."""
        if not model_name or not model_name.strip():
            raise ValueError("Model name cannot be empty.")
        clean_model = model_name.strip()
        self._model_name = clean_model
        if self._api_key:
            self._initialize_client()
        logger.info(f"Gemini active model set to '{self._model_name}'.")

    def get_current_model(self) -> str:
        """Returns the current model name."""
        return self._model_name

    def _initialize_client(self) -> None:
        """Initializes client with current credentials."""
        if not self._api_key:
            self._client = None
            self._legacy_model = None
            return

        if self._use_modern_sdk:
            try:
                from google import genai
                self._client = genai.Client(api_key=self._api_key)
                logger.info(f"Initialized google-genai Client with model '{self._model_name}'.")
                return
            except Exception as e:
                logger.warning(f"Failed to initialize google-genai Client: {e}. Falling back.")

        # Legacy fallback
        try:
            import google.generativeai as legacy_genai
            legacy_genai.configure(api_key=self._api_key)
            self._legacy_model = legacy_genai.GenerativeModel(model_name=self._model_name)
            logger.info("Initialized legacy GenerativeModel.")
        except Exception as e:
            logger.error(f"Failed to initialize legacy GenerativeModel: {e}")
            self._legacy_model = None

    def get_available_models(self) -> List[str]:
        """Returns supported Gemini models."""
        if not self._api_key:
            return list(SUPPORTED_MODELS)

        # Attempt to query live available models if client is active
        if self._client and self._use_modern_sdk:
            try:
                live_models = []
                for m in self._client.models.list():
                    name = getattr(m, "name", str(m))
                    if "gemini" in name.lower():
                        clean_name = name.replace("models/", "")
                        live_models.append(clean_name)
                if live_models:
                    return sorted(list(set(live_models)))
            except Exception as e:
                logger.debug(f"Could not fetch dynamic models list: {e}")

        return list(SUPPORTED_MODELS)

    def test_connection(self, model_name: Optional[str] = None) -> bool:
        """
        Validates API credentials and model accessibility by sending a minimal test request.
        """
        if model_name:
            self.set_model(model_name)

        if not self._api_key:
            logger.warning("Test connection failed: API key not set.")
            return False

        try:
            if self._client and self._use_modern_sdk:
                response = self._client.models.generate_content(
                    model=self._model_name,
                    contents="Ping. Respond with 'PONG'.",
                )
                return bool(response and response.text)
            elif self._legacy_model:
                response = self._legacy_model.generate_content("Ping. Respond with 'PONG'.")
                return bool(response and response.text)
            else:
                self._initialize_client()
                if self._client:
                    return self.test_connection(model_name)
                return False
        except Exception as e:
            logger.error(f"Gemini connection test failed: {e}")
            raise RuntimeError(f"Connection test error: {e}") from e

    def send_message(
        self,
        history: List[Dict[str, Any]],
        model_name: Optional[str] = None,
        system_context: Optional[str] = None,
    ) -> str:
        """
        Sends conversation history with optional system/memory context and returns model response.
        history format: list of dicts with 'role' ('user' or 'model') and 'parts' (list of str or str).
        """
        if model_name:
            self.set_model(model_name)

        if not self._api_key:
            raise RuntimeError("Gemini API key is not configured. Please set your key in Settings.")

        if not history:
            return "No input provided."

        target_model = self._model_name

        # Prepare system instruction
        base_instruction = (
            "You are JARVIS, an advanced, capable, helpful, and polite Windows AI desktop assistant. "
            "Provide clear, concise, accurate, and actionable answers."
        )
        if system_context:
            full_system_instruction = f"{base_instruction}\n\n[USER CONTEXT & MEMORIES]\n{system_context}"
        else:
            full_system_instruction = base_instruction

        if self._use_modern_sdk and self._client:
            return self._send_message_modern(history, target_model, full_system_instruction)
        elif self._legacy_model:
            return self._send_message_legacy(history, target_model, full_system_instruction)
        else:
            self._initialize_client()
            if self._client:
                return self._send_message_modern(history, target_model, full_system_instruction)
            raise RuntimeError("Gemini provider is not initialized. Please verify your API key.")

    def _send_message_modern(
        self,
        history: List[Dict[str, Any]],
        model_name: str,
        system_instruction: str,
    ) -> str:
        """Generates response using google-genai SDK."""
        from google.genai import types

        # Build contents from history
        contents = []
        for turn in history:
            role = turn.get("role", "user")
            # Map roles properly
            mapped_role = "user" if role.lower() == "user" else "model"
            parts = turn.get("parts", [])
            text = parts[0] if isinstance(parts, list) and parts else str(parts)
            contents.append(
                types.Content(
                    role=mapped_role,
                    parts=[types.Part.from_text(text=text)],
                )
            )

        config = types.GenerateContentConfig(
            system_instruction=system_instruction,
            temperature=0.7,
        )

        try:
            response = self._client.models.generate_content(
                model=model_name,
                contents=contents,
                config=config,
            )

            if response and response.text:
                return response.text.strip()

            return "I received an empty response. Please try rephrasing."

        except Exception as e:
            err_str = str(e)
            logger.error(f"Error during Gemini generation: {err_str}")
            if "429" in err_str or "ResourceExhausted" in err_str:
                raise RuntimeError("API quota or rate limit exceeded. Please wait a moment or check your plan.") from e
            if "401" in err_str or "API_KEY_INVALID" in err_str or "PERMISSION_DENIED" in err_str:
                raise RuntimeError("Invalid or unauthorized API key. Please check your credentials in Settings.") from e
            if "404" in err_str or "not found" in err_str.lower():
                raise RuntimeError(f"Model '{model_name}' was not found. Please select an available model.") from e
            raise RuntimeError(f"Gemini API Error: {err_str}") from e

    def _send_message_legacy(
        self,
        history: List[Dict[str, Any]],
        model_name: str,
        system_instruction: str,
    ) -> str:
        """Fallback generator using legacy google.generativeai."""
        try:
            chat_history = history[:-1] if len(history) > 1 else []
            latest_turn = history[-1]
            latest_parts = latest_turn.get("parts", [""])
            latest_prompt = latest_parts[0] if isinstance(latest_parts, list) else str(latest_parts)

            formatted_history = []
            for item in chat_history:
                role = "user" if item.get("role") in ("user", "User") else "model"
                parts = item.get("parts", [""])
                text = parts[0] if isinstance(parts, list) else str(parts)
                formatted_history.append({"role": role, "parts": [text]})

            # Prepend system instruction into the prompt if legacy doesn't support system_instruction directly
            prompt_with_context = f"[System Context: {system_instruction}]\n\n{latest_prompt}"

            chat = self._legacy_model.start_chat(history=formatted_history)
            response = chat.send_message(prompt_with_context)

            if response and response.text:
                return response.text.strip()
            return "Unable to generate response from legacy engine."
        except Exception as e:
            logger.error(f"Legacy generation error: {e}")
            raise RuntimeError(f"Gemini Error: {e}") from e

    def understand_intent(
        self,
        prompt: str,
        model_name: Optional[str] = None,
        system_context: Optional[str] = None,
    ) -> Dict[str, Any]:
        """
        Analyzes prompt and returns structured JSON intent schema.
        Handles JSON parsing, schema extraction, and security validation.
        """
        if not self.is_configured():
            raise RuntimeError("Gemini API key is not configured. Please set your key in Settings.")

        clean_prompt = (prompt or "").strip()
        if not clean_prompt:
            return validate_intent_output({
                "intent_type": "general_chat",
                "response_text": "Please provide a command or question.",
            })

        system_instruction = (
            "You are S.E.N.T.I.A.L., an advanced desktop AI assistant. "
            "Analyze the user request and respond strictly with a single valid JSON object. "
            "Do NOT include markdown block formatting or extra commentary outside the JSON object.\n\n"
            "JSON Schema:\n"
            "{\n"
            '  "intent_type": "launch_app | open_url | open_path | web_search | window_management | create_task | compose_email | system_status | general_chat",\n'
            '  "response_text": "Concise natural language answer or action summary",\n'
            '  "parameters": {\n'
            '     "app_id": "notepad | calculator | explorer | paint | taskmgr | cmd",\n'
            '     "url": "https://...",\n'
            '     "path": "C:\\path\\to\\file_or_folder",\n'
            '     "query": "web search terms",\n'
            '     "action": "minimize | maximize | restore | focus",\n'
            '     "title": "task title",\n'
            '     "to": "recipient email",\n'
            '     "subject": "email subject",\n'
            '     "body": "email body"\n'
            '  },\n'
            '  "urgency": "low | medium | high | critical",\n'
            '  "requires_confirmation": boolean\n'
            "}"
        )
        if system_context:
            system_instruction += f"\n\n[USER CONTEXT & MEMORIES]\n{system_context}"

        history = [{"role": "user", "parts": [clean_prompt]}]

        raw_response = ""
        try:
            raw_response = self.send_message(
                history=history,
                model_name=model_name,
                system_context=system_instruction,
            )
            clean_json = raw_response.strip()
            if clean_json.startswith("```"):
                clean_json = re.sub(r"^```(?:json)?\s*", "", clean_json, flags=re.IGNORECASE)
                clean_json = re.sub(r"\s*```$", "", clean_json)

            data = json.loads(clean_json)
            return validate_intent_output(data)
        except json.JSONDecodeError:
            logger.warning(f"Could not parse JSON intent response. Raw: {raw_response[:100]}")
            return validate_intent_output({
                "intent_type": "general_chat",
                "response_text": raw_response if raw_response else "Unable to parse AI response.",
            })
        except Exception as e:
            logger.error(f"Intent understanding failed: {e}")
            raise
